def safe_float(
    value,
    default=0.0
):
    """
    Safely convert a value to float.
    """

    try:

        return float(value)

    except (
        TypeError,
        ValueError
    ):

        return default


def clamp(
    value,
    minimum,
    maximum
):
    """
    Restrict a value to a safe range.
    """

    return max(
        minimum,
        min(
            maximum,
            value
        )
    )


