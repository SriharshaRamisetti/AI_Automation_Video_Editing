def export_audio_video(
    video,
    topic
):
    """
    Export the audio-processed video.
    """

    output_folder = get_output_folder(
        topic
    )

    output_file = (
        output_folder
        / "audio_video.mp4"
    )

    print()
    print(
        "Rendering audio video..."
    )

    video.write_videofile(
        str(output_file),
        fps=TARGET_FPS,
        codec="libx264",
        audio_codec="aac",
        preset="medium"
    )

    return output_file


