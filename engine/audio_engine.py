# AUDIO PATH RESOLUTION
# ============================================================

def resolve_audio_path(
    audio_path
):
    """
    Convert relative audio paths into
    absolute paths.

    Absolute paths are returned unchanged.
    """

    if not audio_path:

        return None

    audio_path = Path(
        audio_path
    )

    if audio_path.is_absolute():

        return audio_path

    return BASE_DIR / audio_path


def validate_audio_path(
    audio_path
):
    """
    Check whether an audio file exists.
    """

    path = resolve_audio_path(
        audio_path
    )

    if path is None:

        return False

    return (
        path.exists()
        and path.is_file()
    )


# ============================================================
# AUDIO FILE DISCOVERY
# ============================================================

def find_audio_files(
    directory
):
    """
    Recursively find supported audio files.
    """

    directory = Path(
        directory
    )

    if not directory.exists():

        return []

    audio_files = []

    for file_path in directory.rglob("*"):

        if not file_path.is_file():

            continue

        if (
            file_path.suffix.lower()
            in SUPPORTED_AUDIO_EXTENSIONS
        ):

            audio_files.append(
                file_path
            )

    audio_files.sort()

    return audio_files


# ============================================================
# LOAD AUDIO
# ============================================================

def load_audio_clip(
    audio_path
):
    """
    Load an audio file with MoviePy.
    """

    absolute_path = resolve_audio_path(
        audio_path
    )

    if absolute_path is None:

        raise FileNotFoundError(
            "Audio path is empty."
        )

    if not absolute_path.exists():

        raise FileNotFoundError(
            f"Audio file not found:\n"
            f"{absolute_path}"
        )

    print(
        f"    Loading audio: "
        f"{absolute_path.name}"
    )

    return AudioFileClip(
        str(absolute_path)
    )


# ============================================================
# AUDIO DURATION
# ============================================================

def get_audio_duration(
    audio_clip
):
    """
    Return audio duration safely.
    """

    if audio_clip is None:

        return 0.0

    return safe_float(
        getattr(
            audio_clip,
            "duration",
            0
        ),
        0.0
    )


# ============================================================
# AUDIO VOLUME
# ============================================================

def set_audio_volume(
    audio_clip,
    volume
):
    """
    Set audio volume.

    Examples:

        1.0 = 100%
        0.5 = 50%
        0.2 = 20%
    """

    if audio_clip is None:

        return None

    volume = clamp(
        safe_float(
            volume,
            1.0
        ),
        0.0,
        2.0
    )

    return audio_clip.with_volume_scaled(
        volume
    )


# ============================================================
# AUDIO TRIMMING
# ============================================================

def trim_audio_to_duration(
    audio_clip,
    duration
):
    """
    Trim audio to a maximum duration.
    """

    if audio_clip is None:

        return None

    duration = safe_float(
        duration,
        0
    )

    if duration <= 0:

        return audio_clip

    audio_duration = get_audio_duration(
        audio_clip
    )

    if audio_duration <= duration:

        return audio_clip

    return audio_clip.subclipped(
        0,
        duration
    )


# ============================================================
# AUDIO LOOPING
# ============================================================

def loop_audio_to_duration(
    audio_clip,
    duration
):
    """
    Repeat an audio clip until it reaches
    the requested duration.

    The final result is trimmed exactly
    to the requested duration.
    """

    if audio_clip is None:

        return None

    duration = safe_float(
        duration,
        0
    )

    if duration <= 0:

        return audio_clip

    original_duration = get_audio_duration(
        audio_clip
    )

    if original_duration <= 0:

        return audio_clip

    if original_duration >= duration:

        return audio_clip.subclipped(
            0,
            duration
        )

    from moviepy import concatenate_audioclips

    clips = []

    current_duration = 0.0

    while current_duration < duration:

        remaining = (
            duration
            - current_duration
        )

        if original_duration <= remaining:

            piece = audio_clip

        else:

            piece = audio_clip.subclipped(
                0,
                remaining
            )

        clips.append(
            piece
        )

        current_duration += min(
            original_duration,
            remaining
        )

        if len(clips) > 1000:

            raise RuntimeError(
                "Audio looping exceeded "
                "the safety limit."
            )

    return concatenate_audioclips(
        clips
    )


# ============================================================
# AUDIO OFFSET
# ============================================================

def position_audio(
    audio_clip,
    start_time
):
    """
    Place an audio clip at a specific
    timeline position.
    """

    if audio_clip is None:

        return None

    start_time = max(
        0.0,
        safe_float(
            start_time,
            0
        )
    )

    return audio_clip.with_start(
        start_time
    )


# ============================================================
# FADE AUDIO
# ============================================================

def fade_audio_in(
    audio_clip,
    duration=0.5
):
    """
    Fade audio in.
    """

    if audio_clip is None:

        return None

    duration = min(
        safe_float(
            duration,
            0.5
        ),
        get_audio_duration(
            audio_clip
        ) / 2
    )

    if duration <= 0:

        return audio_clip

    from moviepy.audio.fx import AudioFadeIn

    return audio_clip.with_effects([
        AudioFadeIn(
            duration
        )
    ])


def fade_audio_out(
    audio_clip,
    duration=0.5
):
    """
    Fade audio out.
    """

    if audio_clip is None:

        return None

    duration = min(
        safe_float(
            duration,
            0.5
        ),
        get_audio_duration(
            audio_clip
        ) / 2
    )

    if duration <= 0:

        return audio_clip

    from moviepy.audio.fx import AudioFadeOut

    return audio_clip.with_effects([
        AudioFadeOut(
            duration
        )
    ])


# ============================================================
# VOICEOVER
# ============================================================

def prepare_voiceover(
    audio_path,
    start_time,
    end_time,
    volume=DEFAULT_VOICE_VOLUME
):
    """
    Prepare a voiceover track for a scene.
    """

    if not audio_path:

        return None

    audio = load_audio_clip(
        audio_path
    )

    scene_duration = (
        safe_float(end_time)
        - safe_float(start_time)
    )

    if scene_duration <= 0:

        audio.close()

        return None

    audio = trim_audio_to_duration(
        audio,
        scene_duration
    )

    audio = set_audio_volume(
        audio,
        volume
    )

    audio = fade_audio_in(
        audio,
        0.05
    )

    audio = fade_audio_out(
        audio,
        0.10
    )

    audio = position_audio(
        audio,
        start_time
    )

    return audio


# ============================================================
# BACKGROUND MUSIC
# ============================================================

def prepare_background_music(
    audio_path,
    total_duration,
    volume=DEFAULT_MUSIC_VOLUME
):
    """
    Prepare background music.

    Music is looped when it is shorter
    than the complete video.
    """

    if not audio_path:

        return None

    music = load_audio_clip(
        audio_path
    )

    music = loop_audio_to_duration(
        music,
        total_duration
    )

    music = set_audio_volume(
        music,
        volume
    )

    music = fade_audio_in(
        music,
        1.0
    )

    music = fade_audio_out(
        music,
        1.0
    )

    music = position_audio(
        music,
        0
    )

    return music


# ============================================================
