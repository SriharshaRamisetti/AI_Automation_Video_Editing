# ============================================================
# COLLECT AUDIO TRACKS
# ============================================================

def build_audio_tracks(
    timeline,
    total_duration
):
    """
    Build all voiceover, music and SFX
    tracks from the timeline.
    """

    voice_tracks = []
    music_tracks = []
    sfx_tracks = []

    print()
    print("=" * 70)
    print("BUILDING AUDIO TRACKS")
    print("=" * 70)

    for scene in timeline:

        scene_number = scene.get(
            "scene_number",
            "unknown"
        )

        start_time = safe_float(
            scene.get(
                "start",
                0
            )
        )

        end_time = safe_float(
            scene.get(
                "end",
                start_time
            )
        )

        audio = get_scene_audio_structure(
            scene
        )

        # ----------------------------------------------------
        # VOICEOVER
        # ----------------------------------------------------

        voiceover = audio.get(
            "voiceover"
        )

        voiceover_path = (
            resolve_voiceover_path(
                voiceover
            )
        )

        if voiceover_path:

            print()
            print(
                f"Scene {scene_number}: "
                "Voiceover"
            )

            voice = prepare_voiceover(
                voiceover_path,
                start_time,
                end_time,
                DEFAULT_VOICE_VOLUME
            )

            if voice is not None:

                voice_tracks.append(
                    voice
                )

        # ----------------------------------------------------
        # MUSIC
        # ----------------------------------------------------

        music = audio.get(
            "music"
        )

        music_path = (
            resolve_music_path(
                music
            )
        )

        if music_path:

            music_volume = safe_float(
                music.get(
                    "volume",
                    DEFAULT_MUSIC_VOLUME
                ),
                DEFAULT_MUSIC_VOLUME
            )

            print()
            print(
                f"Scene {scene_number}: "
                "Music"
            )

            music_clip = load_audio_clip(
                music_path
            )

            scene_duration = (
                end_time
                - start_time
            )

            music_clip = (
                loop_audio_to_duration(
                    music_clip,
                    scene_duration
                )
            )

            music_clip = set_audio_volume(
                music_clip,
                music_volume
            )

            music_clip = position_audio(
                music_clip,
                start_time
            )

            music_tracks.append(
                music_clip
            )

        # ----------------------------------------------------
        # SOUND EFFECTS
        # ----------------------------------------------------

        sound_effects = audio.get(
            "sound_effects",
            []
        )

        if not isinstance(
            sound_effects,
            list
        ):

            sound_effects = []

        for sound_effect in sound_effects:

            if not isinstance(
                sound_effect,
                dict
            ):

                continue

            sfx_path = sound_effect.get(
                "file"
            )

            if not sfx_path:

                continue

            sfx_start = safe_float(
                sound_effect.get(
                    "start",
                    start_time
                ),
                start_time
            )

            sfx_volume = safe_float(
                sound_effect.get(
                    "volume",
                    DEFAULT_SFX_VOLUME
                ),
                DEFAULT_SFX_VOLUME
            )

            print()
            print(
                f"Scene {scene_number}: "
                "Sound effect"
            )

            sfx = prepare_sound_effect(
                sfx_path,
                sfx_start,
                sfx_volume
            )

            if sfx is not None:

                sfx_tracks.append(
                    sfx
                )

    return {
        "voice": voice_tracks,
        "music": music_tracks,
        "sfx": sfx_tracks
    }


# ============================================================
# MUSIC DUCKING
# ============================================================

def apply_voiceover_ducking(
    music_tracks,
    voice_tracks,
    duck_volume=DEFAULT_VOICE_DUCKING
):
    """
    Reduce music volume when voiceover exists.

    This provides the classic:

        Voice = foreground
        Music = background

    effect.
    """

    if not music_tracks:

        return music_tracks

    if not voice_tracks:

        return music_tracks

    duck_volume = clamp(
        safe_float(
            duck_volume,
            DEFAULT_VOICE_DUCKING
        ),
        0.0,
        1.0
    )

    processed_music = []

    for music in music_tracks:

        processed_music.append(
            music.with_volume_scaled(
                duck_volume
            )
        )

    return processed_music


# ============================================================
# COMPOSITE AUDIO
# ============================================================

def combine_audio_tracks(
    audio_tracks,
    total_duration
):
    """
    Combine voice, music and SFX into
    one audio track.
    """

    voice_tracks = audio_tracks.get(
        "voice",
        []
    )

    music_tracks = audio_tracks.get(
        "music",
        []
    )

    sfx_tracks = audio_tracks.get(
        "sfx",
        []
    )

    music_tracks = (
        apply_voiceover_ducking(
            music_tracks,
            voice_tracks
        )
    )

    all_tracks = []

    all_tracks.extend(
        voice_tracks
    )

    all_tracks.extend(
        music_tracks
    )

    all_tracks.extend(
        sfx_tracks
    )

    if not all_tracks:

        return None

    print()
    print(
        f"Combining {len(all_tracks)} "
        "audio tracks..."
    )

    final_audio = CompositeAudioClip(
        all_tracks
    )

    final_audio = final_audio.with_duration(
        total_duration
    )

    return final_audio


# ============================================================
# AUDIO VALIDATION
# ============================================================

def validate_audio_configuration(
    timeline
):
    """
    Validate audio configuration without
    actually loading every audio file.
    """

    errors = []

    for scene in timeline:

        scene_number = scene.get(
            "scene_number",
            "unknown"
        )

        audio = get_scene_audio_structure(
            scene
        )

        voiceover = audio.get(
            "voiceover"
        )

        if isinstance(
            voiceover,
            dict
        ):

            voice_file = voiceover.get(
                "file"
            )

            if voice_file:

                if not validate_audio_path(
                    voice_file
                ):

                    errors.append(
                        f"Scene {scene_number}: "
                        f"voiceover not found: "
                        f"{voice_file}"
                    )

        music = audio.get(
            "music"
        )

        if isinstance(
            music,
            dict
        ):

            music_file = music.get(
                "file"
            )

            if music_file:

                if not validate_audio_path(
                    music_file
                ):

                    errors.append(
                        f"Scene {scene_number}: "
                        f"music not found: "
                        f"{music_file}"
                    )

        sound_effects = audio.get(
            "sound_effects",
            []
        )

        if isinstance(
            sound_effects,
            list
        ):

            for index, sfx in enumerate(
                sound_effects
            ):

                if not isinstance(
                    sfx,
                    dict
                ):

                    continue

                sfx_file = sfx.get(
                    "file"
                )

                if sfx_file:

                    if not validate_audio_path(
                        sfx_file
                    ):

                        errors.append(
                            f"Scene {scene_number}: "
                            f"SFX #{index + 1} "
                            f"not found: "
                            f"{sfx_file}"
                        )

    return errors


# ============================================================
# ATTACH AUDIO TO VIDEO
# ============================================================

def attach_audio_to_video(
    video,
    audio
):
    """
    Attach the final composite audio
    to the video.
    """

    if video is None:

        raise ValueError(
            "Video cannot be None."
        )

    if audio is None:

        print()
        print(
            "WARNING: No audio tracks "
            "were configured."
        )

        return video

    return video.with_audio(
        audio
    )


