def process_topic(
    topic
):
    """
    Complete audio pipeline.

    Input:

        How to manage fear

    Reads:

        projects/
        └── how_to_manage_fear/
            └── timeline.json

        output/
        └── how_to_manage_fear/
            └── effects_video.mp4

    Produces:

        output/
        └── how_to_manage_fear/
            └── audio_video.mp4
    """

    print()
    print("=" * 70)
    print("AI VIDEO AUTOMATION")
    print("AUDIO ENGINE")
    print("=" * 70)

    timeline_file = find_timeline(
        topic
    )

    effects_video = find_effects_video(
        topic
    )

    # --------------------------------------------------------
    # CHECK TIMELINE
    # --------------------------------------------------------

    if not timeline_file.exists():

        print()
        print(
            "ERROR: timeline.json not found."
        )

        print()
        print(
            f"Expected:\n{timeline_file}"
        )

        print()

        return None

    # --------------------------------------------------------
    # CHECK VIDEO
    # --------------------------------------------------------

    if not effects_video.exists():

        print()
        print(
            "ERROR: effects_video.mp4 "
            "not found."
        )

        print()
        print(
            f"Expected:\n{effects_video}"
        )

        print()
        print(
            "Run effects.py first."
        )

        return None

    video = None
    final_audio = None

    audio_tracks = {
        "voice": [],
        "music": [],
        "sfx": []
    }

    try:

        # ----------------------------------------------------
        # LOAD TIMELINE
        # ----------------------------------------------------

        timeline_project = load_timeline(
            topic
        )

        timeline = timeline_project.get(
            "timeline",
            []
        )

        if not timeline:

            raise ValueError(
                "Timeline contains no scenes."
            )

        # ----------------------------------------------------
        # VALIDATE AUDIO SETTINGS
        # ----------------------------------------------------

        validation_errors = (
            validate_audio_configuration(
                timeline
            )
        )

        if validation_errors:

            print()
            print(
                "AUDIO VALIDATION WARNINGS"
            )

            for error in validation_errors:

                print(
                    f"  - {error}"
                )

            print()

        # ----------------------------------------------------
        # TOTAL DURATION
        # ----------------------------------------------------

        total_duration = safe_float(
            timeline_project.get(
                "total_duration",
                0
            )
        )

        if total_duration <= 0:

            total_duration = (
                timeline[-1].get(
                    "end",
                    0
                )
            )

            total_duration = safe_float(
                total_duration,
                0
            )

        if total_duration <= 0:

            raise ValueError(
                "Unable to determine "
                "video duration."
            )

        # ----------------------------------------------------
        # LOAD VIDEO
        # ----------------------------------------------------

        print()
        print(
            "Loading effects video:"
        )

        print(
            effects_video
        )

        video = VideoFileClip(
            str(
                effects_video
            )
        )

        video = video.with_fps(
            TARGET_FPS
        )

        # ----------------------------------------------------
        # BUILD AUDIO
        # ----------------------------------------------------

        audio_tracks = build_audio_tracks(
            timeline,
            total_duration
        )

        final_audio = combine_audio_tracks(
            audio_tracks,
            total_duration
        )

        # ----------------------------------------------------
        # ATTACH AUDIO
        # ----------------------------------------------------

        final_video = attach_audio_to_video(
            video,
            final_audio
        )

        # ----------------------------------------------------
        # EXPORT
        # ----------------------------------------------------

        output_file = export_audio_video(
            final_video,
            topic
        )

        # ----------------------------------------------------
        # SAVE STATUS
        # ----------------------------------------------------

        save_audio_status(
            topic,
            timeline_project,
            output_file
        )

        print()
        print("=" * 70)
        print(
            "AUDIO ENGINE COMPLETED"
        )
        print("=" * 70)

        print()
        print(
            "Audio video:"
        )

        print(
            output_file
        )

        print()

        return output_file

    except Exception as error:

        print()
        print("=" * 70)
        print(
            "AUDIO ENGINE ERROR"
        )
        print("=" * 70)

        print()
        print(
            f"Error: {error}"
        )

        print()

        raise

    finally:

        close_audio(
            final_audio
        )

        close_audio_tracks(
            audio_tracks
        )

        close_video(
            video
        )


