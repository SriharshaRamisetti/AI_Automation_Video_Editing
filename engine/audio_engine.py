"""
audio_engine.py

Audio Engine
------------

Responsibilities:

1. Load timeline.json.
2. Locate the effects-processed video.
3. Read audio configuration from timeline.json.
4. Load voiceover audio.
5. Load background music.
6. Load sound effects.
7. Trim audio to the required duration.
8. Loop music when necessary.
9. Control volume.
10. Duck background music underneath voiceover.
11. Synchronize audio with the video timeline.
12. Combine all audio tracks.
13. Attach the final audio to the processed video.
14. Export the audio-processed video.

This file does NOT handle:

- subtitle_engine.py
- renderer.py
"""

