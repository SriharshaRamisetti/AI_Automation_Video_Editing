def prepare_sound_effect(
    audio_path,
    start_time,
    volume=DEFAULT_SFX_VOLUME
):
    """
    Prepare one sound effect.
    """

    if not audio_path:

        return None

    sfx = load_audio_clip(
        audio_path
    )

    sfx = set_audio_volume(
        sfx,
        volume
    )

    sfx = fade_audio_in(
        sfx,
        0.03
    )

    sfx = fade_audio_out(
        sfx,
        0.05
    )

    sfx = position_audio(
        sfx,
        start_time
    )

    return sfx


