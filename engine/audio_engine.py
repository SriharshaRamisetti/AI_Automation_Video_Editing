def normalize_text(text):
    """
    Normalize text for folder/file matching.
    """

    if text is None:
        return ""

    text = str(text)

    text = text.lower()

    text = text.replace("-", " ")
    text = text.replace("_", " ")

    return " ".join(text.split())


def topic_to_folder_name(topic):
    """
    Convert:

        How to manage fear

    into:

        how_to_manage_fear
    """

    return normalize_text(topic).replace(
        " ",
        "_"
    )


